List<FixedTrainingExercise> filterFixedTrainingExercises({
  String query = '',
  String? category,
}) {
  final normalizedQuery = query.trim().toLowerCase();
  return fixedTrainingExercises
      .where(
        (exercise) =>
            (category == null || exercise.category == category) &&
            (normalizedQuery.isEmpty ||
                exercise.name.toLowerCase().contains(normalizedQuery) ||
                exercise.englishName.toLowerCase().contains(normalizedQuery)),
      )
      .toList(growable: false);
}
